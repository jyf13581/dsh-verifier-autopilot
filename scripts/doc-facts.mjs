// Code-derived documentation facts (review R7 7.1).
//
// The README's defaults table used to be typed by hand and drifted from the
// schema (and HANDOFF's copy drifted further: maxTokens 8192 vs 64000, P
// fallback 1 vs 0, "maxWorkers=1" vs auto 4). This script renders it from the
// built config schema and the exported operational limits instead:
//
//   node scripts/doc-facts.mjs --write   rewrite the generated block in README.md
//   node scripts/doc-facts.mjs --check   exit 1 when README.md is stale
//
// Only the "notes" column is prose. Values, ranges and choices come from
// `Config.dict` (schema meta), so they cannot disagree with the code. Test
// counts are deliberately NOT rendered anywhere: CI's spec reporter prints the
// authoritative number on every run. scripts/tests/doc-truth.test.mjs runs
// --check's logic in `npm test`. Requires `lib/` (npm run build:host).

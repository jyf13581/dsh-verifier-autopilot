const cell = (value) => String(value).replace(/\|/g, '\\|')
const code = (value) => '`' + cell(value === '' ? "''" : value) + '`'

function allowed(schema) {
  if (schema.type === 'union') return schema.list.map((item) => code(item.value)).join(' / ')
  if (schema.type === 'boolean') return '`true` / `false`'
  const meta = schema.meta ?? {}
  if (schema.type === 'number' && meta.min !== undefined && meta.max !== undefined) return code(meta.min) + '..' + code(meta.max) + (meta.step && meta.step !== 1 ? ' step ' + meta.step : '')
  if (schema.type === 'string' && meta.max !== undefined) return 'string, at most ' + meta.max + ' chars'
  return schema.type
}

export async function renderDefaults() {
  const { Config } = await lib('config.js')
  const { API_RATE_LIMITS } = await lib('api.js')
  const { SELECTIONS_HISTORY_LIMIT, PREFLIGHT_OK_TTL_MS, AUTO_VERIFIER_WORKERS } = await lib('selection/host.js')
  const constants = { AUTO_VERIFIER_WORKERS }
  const note = (key) => (NOTES[key] ?? '').replace(/\{(\w+)\}/g, (whole, name) => {
    if (!(name in constants)) throw new Error('doc-facts: unknown placeholder ' + whole)
    return String(constants[name])
  })
  const rows = ['| Setting | Default | Allowed | Notes |', '|---|---|---|---|']
  const missing = []
  for (const [key, schema] of Object.entries(Config.dict)) {
    if (!NOTES[key]) missing.push(key)
    rows.push('| `' + key + '` | ' + code(schema.meta?.default) + ' | ' + allowed(schema) + ' | ' + cell(note(key)) + ' |')
  }
  if (missing.length > 0) throw new Error('doc-facts: no note for config key(s) ' + missing.join(', ') + ' (add one to NOTES)')
  const limits = [
    '| Limit | Value |', '|---|---|',
    '| `POST /select` admissions | ' + API_RATE_LIMITS.selectPerHour + ' per hour (sliding window) |',
    '| `POST /eval` / `/probe` / `/verify` | ' + API_RATE_LIMITS.evalPerMinute + ' / ' + API_RATE_LIMITS.probePerMinute + ' / ' + API_RATE_LIMITS.verifyPerMinute + ' per minute |',
    '| selection ledger window | ' + SELECTIONS_HISTORY_LIMIT + ' records (audit packs outside it are collected) |',
    '| verifier preflight success cache | ' + PREFLIGHT_OK_TTL_MS / 60_000 + ' minutes |',
  ]
  return [BEGIN, '', rows.join('\n'), '', limits.join('\n'), '', END].join('\n')
}


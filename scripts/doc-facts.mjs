/** Drift findings for one authoritative document (review R7 7.1):
 *  hand-written test counts (CI prints the real one), author-machine paths,
 *  "`key` ... default X" prose that disagrees with the schema, and margin-gate
 *  values other than the shipped threshold. */
export function lintDoc(text, defaults) {
  const findings = []
  const escape = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  text.split('\n').forEach((line, index) => {
    const at = 'line ' + (index + 1)
    if (/\b(\d{3})\s*\/\s*\1\b|\b\d{3} (?:regressions|tests)\b/.test(line)) findings.push(at + ': hand-written test count')
    if (/\b[CD]:[\\/]/.test(line)) findings.push(at + ': author-machine path')
    for (const [key, value] of Object.entries(defaults)) {
      const claim = new RegExp('`?\\b' + escape(key) + '\\b`?[^|\\n]{0,40}?\\bdefaults?\\b(?: is| to|:|=)?\\s*`?([\\w./:-]+)').exec(line)
      const written = claim?.[1]
      if (written && written !== String(value) && !(value === '' && (written === 'empty' || written === "''"))) findings.push(at + ': ' + key + ' default written as ' + written + ', schema says ' + JSON.stringify(value))
    }
    if (/margin gate|selectionMarginThreshold/.test(line)) {
      for (const decimal of line.match(/\b0\.0\d+\b/g) ?? []) {
        if (Number(decimal) !== defaults.selectionMarginThreshold) findings.push(at + ': margin value ' + decimal + ', shipped threshold is ' + defaults.selectionMarginThreshold)
      }
    }
  })
  return findings
}

export function replaceBlock(text, block) {
  const start = text.indexOf(BEGIN)
  const end = text.indexOf(END)
  if (start < 0 || end < start) throw new Error('doc-facts: README.md has no generated defaults block')
  return text.slice(0, start) + block + text.slice(end + END.length)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const readme = path.join(root, 'README.md')
  const current = readFileSync(readme, 'utf8')
  const next = replaceBlock(current, await renderDefaults())
  if (process.argv.includes('--write')) {
    if (next !== current) writeFileSync(readme, next)
    console.log(next === current ? 'doc-facts: README.md already current' : 'doc-facts: README.md updated')
  } else if (next !== current) {
    console.error('doc-facts: README.md defaults block is stale; run node scripts/doc-facts.mjs --write')
    process.exit(1)
  } else {
    console.log('doc-facts: README.md current')
  }
}
